"""Generate the demo story's synthetic data. Not real fields, operators or volumes.

Usage: uv run python examples/demo/make_data.py
"""

from __future__ import annotations

import math
import random
from pathlib import Path

import pandas as pd

OUT = Path(__file__).parent / "data"
rng = random.Random(42)


def profile(peak, start, plateau, decline, years):
    out = []
    for y in years:
        t = y - start
        if t < 0:
            v = 0.0
        elif t < 3:
            v = peak * (0.04 + 0.96 * t / 3)
        elif t < 3 + plateau:
            v = peak
        else:
            v = peak * math.exp(-decline * (t - 3 - plateau))
        out.append(round(v, 2))
    return out


def main() -> None:
    OUT.mkdir(exist_ok=True)
    years = list(range(2000, 2026))
    fields = [  # name, peak (k Sm3 o.e./d), start, plateau years, decline, operator
        ("Field A", 52, 1998, 2, 0.13, "Operator A"),
        ("Field B", 38, 2001, 3, 0.16, "Operator B"),
        ("Field C", 44, 2004, 14, 0.12, "Operator A"),
        ("Field D", 27, 2006, 2, 0.18, "Operator C"),
        ("Field E", 31, 2011, 3, 0.15, "Operator B"),
        ("Field F", 22, 2013, 9, 0.10, "Operator D"),
        ("Field G", 18, 2016, 2, 0.20, "Operator E"),
    ]
    rows, summary = [], []
    for name, peak, start, plateau, decline, op in fields:
        vals = profile(peak, start, plateau, decline, years)
        rows += [{"year": y, "field": name, "kboed": v} for y, v in zip(years, vals, strict=True)]
        summary.append(
            {
                "field": name,
                "operator": op,
                "start": max(start, 2000),
                "peak_kboed": peak,
                "plateau_years": plateau,
                "kboed_2025": vals[-1],
                "cum_msm3": round(sum(vals) * 365 / 1000, 1),
            }
        )
    pd.DataFrame(rows).to_csv(OUT / "production.csv", index=False)
    pd.DataFrame(summary).to_csv(OUT / "fields.csv", index=False)

    decades = ["1960s", "1970s", "1980s", "1990s", "2000s", "2010s", "2020s"]
    pd.DataFrame(
        {
            "decade": decades,
            "discoveries": [4, 26, 41, 52, 47, 38, 19],
            "avg_msm3": [410, 230, 96, 47, 30, 22, 15],
        }
    ).to_csv(OUT / "decades.csv", index=False)

    price = {
        2005: 0.8,
        2006: 0.9,
        2007: 1,
        2008: 1.2,
        2009: 0.8,
        2010: 0.95,
        2011: 1.15,
        2012: 1.2,
        2013: 1.18,
        2014: 1.05,
        2015: 0.6,
        2016: 0.5,
        2017: 0.6,
        2018: 0.75,
        2019: 0.8,
        2020: 0.5,
        2021: 0.75,
        2022: 1.1,
        2023: 0.95,
        2024: 0.9,
    }
    wells = [
        {"year": y, "quarter": q, "wells": max(0, round(11 * p * s + rng.gauss(0, 1.2)))}
        for y, p in price.items()
        for q, s in zip(["Q1", "Q2", "Q3", "Q4"], [0.8, 1.05, 1.15, 1.0], strict=True)
    ]
    pd.DataFrame(wells).to_csv(OUT / "wells.csv", index=False)
    write_header(OUT / "header.json")
    print(f"wrote {OUT}")


def write_header(path: Path) -> None:
    """A synthetic header band (docs/header-contract.md): three gently folded reflectors
    under a wavelet, with a little noise, and the surfaces that made them. Not a real
    section; the demo story says so."""
    import base64
    import json

    import numpy as np

    g = np.random.default_rng(7)
    n, ns, dt = 320, 110, 4.0
    t = 1000.0 + np.arange(ns) * dt  # ms, 1000 to 1436
    x = np.linspace(0, 1, n)
    fold = 26 * np.sin(2.9 * x + 0.4) + 11 * np.cos(7.1 * x) + 90 * x
    tops = {
        "top of the upper unit": 1090 + fold,
        "reservoir top": 1190 + fold * 0.8,
        "reservoir base": 1245 + fold * 0.7,
        "basement": 1360 + fold * 0.4,
    }
    refl = g.normal(0, 0.012, (n, ns))
    for k, surface in enumerate(tops.values()):
        coef = (0.08, 0.12, -0.11, 0.09)[k]
        j = (surface - t[0]) / dt
        lo = np.clip(np.floor(j).astype(int), 0, ns - 2)
        w = j - lo
        refl[np.arange(n), lo] += coef * (1 - w)
        refl[np.arange(n), lo + 1] += coef * w
    f, half = 28.0, 60.0
    tw = np.arange(-half, half + dt / 2, dt) / 1000.0
    ricker = (1 - 2 * (np.pi * f * tw) ** 2) * np.exp(-((np.pi * f * tw) ** 2))
    trace = np.array([np.convolve(r, ricker, mode="same") for r in refl])
    clip = float(np.percentile(np.abs(trace), 99))
    q = np.rint(np.clip(trace / clip, -1, 1) * 127).astype(np.int8)
    payload = {
        "schema_version": 1,
        "kind": "header",
        "title": "SubScout demo: a synthetic header band",
        "attribution": "Synthetic section generated by examples/demo/make_data.py; no real survey.",
        "source_file": "make_data.py",
        "domain": {
            "vertical": "time",
            "vertical_unit": "ms",
            "quantity": "amplitude",
            "quantity_unit": "unitless",
        },
        "polarity": "normal",
        "label": "synthetic section, 1000 to 1436 ms; the reservoir top in the highlight colour",
        "n_traces": n,
        "n_samples": ns,
        "samples": t.tolist(),
        "amp_clip": clip,
        "amp_b64": base64.b64encode(np.ascontiguousarray(q).tobytes()).decode("ascii"),
        "highlight": "reservoir top",
        "surfaces": [
            {"label": name, "time": np.round(s, 1).tolist(), "cover": 1.0} for name, s in tops.items()
        ],
        "notes": [
            "amplitudes are relative",
            "the surfaces are the model's own boundaries, illustrative names",
        ],
    }
    path.write_text(json.dumps(payload), encoding="utf-8")


if __name__ == "__main__":
    main()
